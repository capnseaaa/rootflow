"""Rootflow's sound effects: short recorded samples played on the GBA's DirectSound channel A.

Two steps:
  python3 tools/make_sfx.py --import   convert the chosen files from third_party/sfx (the downloaded
                                       CC0 packs) into rootflow/sfx/<name>.raw (8-bit, mono, RATE Hz)
  python3 tools/make_sfx.py            turn rootflow/sfx/*.raw into src/sfx.h (run by build.sh)

The .raw files are kept in the repo, so building never needs the downloads.
To change a sound: edit SFX below, run --import, rebuild. Credits are in rootflow/sfx/CREDITS.md.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKS = os.path.join(ROOT, "..", "third_party", "sfx")
SFX_DIR = os.path.join(ROOT, "sfx")
OUT = os.path.join(ROOT, "src", "sfx.h")
RATE = 13379                      # a common GBA sample rate (timer reload 65536 - 1254)
P512 = "subspace_512/files/The Essential Retro Video Game Sound Effects Collection [512 sounds] By Juhani Junkala"

# name: (source file under third_party/sfx, longest length in seconds, volume 0..1)
SFX = {
    "bloom":     (P512 + "/General Sounds/Positive Sounds/sfx_sounds_powerup13.wav", 0.45, 0.8),
    "wake":      (P512 + "/General Sounds/Positive Sounds/sfx_sounds_powerup16.wav", 0.70, 0.8),
    "join":      (P512 + "/General Sounds/Fanfares/sfx_sounds_fanfare2.wav", 0.30, 0.8),
    "bridge":    ("kenney_rpg/files/Audio/bookPlace1.ogg", 0.30, 1.0),
    "rock":      (P512 + "/General Sounds/Impacts/sfx_sounds_impact12.wav", 0.30, 0.9),
    "gust":      ("kenney_rpg/files/Audio/cloth2.ogg", 0.42, 1.0),
    "gift":      ("frogpog/pick_up.wav", 0.20, 0.8),
    "build":     ("kenney_interface/files/Audio/drop_002.ogg", 0.20, 1.0),
    "remove":    ("kenney_interface/files/Audio/minimize_003.ogg", 0.22, 1.0),
    "chest":     (P512 + "/General Sounds/Fanfares/sfx_sounds_fanfare1.wav", 0.52, 0.8),
    "home":      (P512 + "/General Sounds/Positive Sounds/sfx_sounds_powerup2.wav", 0.75, 0.8),
    "quest":     ("frogpog/level_up.wav", 0.95, 0.8),
    "pump_on":   (P512 + "/General Sounds/Negative Sounds/sfx_sounds_negative2.wav", 0.76, 0.8),
    "pump_off":  ("kenney_rpg/files/Audio/metalPot2.ogg", 0.60, 1.0),
    "menu_move": (P512 + "/General Sounds/Menu Sounds/sfx_menu_move2.wav", 0.07, 0.7),
    "menu_open": (P512 + "/General Sounds/Menu Sounds/sfx_menu_select1.wav", 0.35, 0.7),
    "menu_back": ("kenney_interface/files/Audio/back_003.ogg", 0.10, 1.0),
    "save":      ("kenney_interface/files/Audio/confirmation_002.ogg", 0.53, 1.0),
    "fail":      ("kenney_interface/files/Audio/error_004.ogg", 0.12, 1.0),
}
ORDER = list(SFX)


def convert(name, src, max_len, gain):
    """Decode with ffmpeg to mono 16-bit at RATE, trim leading silence, cap the length, fade the
    tail, normalize, and write signed 8-bit samples."""
    pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", os.path.join(PACKS, src), "-ac", "1", "-ar", str(RATE),
                          "-f", "s16le", "-"], capture_output=True, check=True).stdout
    s = [int.from_bytes(pcm[i:i + 2], "little", signed=True) for i in range(0, len(pcm) - 1, 2)]
    start = next((i for i, v in enumerate(s) if abs(v) > 600), 0)
    s = s[start:start + int(max_len * RATE)]
    peak = max(1, max(abs(v) for v in s))
    fade = int(0.03 * RATE)
    out = bytearray()
    for i, v in enumerate(s):
        f = min(1.0, (len(s) - i) / fade)
        x = int(v / peak * 120 * gain * f)
        out.append(max(-127, min(127, x)) & 0xFF)
    with open(os.path.join(SFX_DIR, name + ".raw"), "wb") as fh:
        fh.write(out)
    print(f"{name}: {len(out)} samples ({len(out) / RATE:.2f} s) from {src.split('/')[-1]}")


def write_header():
    lines = ["// Generated by tools/make_sfx.py from rootflow/sfx/*.raw. Do not edit by hand.", "#pragma once", ""]
    lines.append(f"#define SFX_RATE {RATE}")
    lines.append(f"#define NUM_SFX {len(ORDER)}")
    for i, name in enumerate(ORDER):
        lines.append(f"#define SFX_{name.upper()} {i}")
    total = 0
    for name in ORDER:
        data = open(os.path.join(SFX_DIR, name + ".raw"), "rb").read()
        data += bytes(256 + (-len(data)) % 16)     # silence after the end (the DMA reads ahead), 16-byte aligned
        total += len(data)
        vals = ", ".join(str(b - 256 if b > 127 else b) for b in data)
        lines.append(f"__attribute__((aligned(4))) static const signed char sfx_{name}[{len(data)}] = {{ {vals} }};")
    lines.append("static const signed char *const sfx_data[NUM_SFX] = { "
                 + ", ".join(f"sfx_{n}" for n in ORDER) + " };")
    lines.append("static const unsigned short sfx_len[NUM_SFX] = { "
                 + ", ".join(str(os.path.getsize(os.path.join(SFX_DIR, n + '.raw'))) for n in ORDER) + " };")
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({total} bytes of samples)")


def main():
    os.makedirs(SFX_DIR, exist_ok=True)
    if "--import" in sys.argv:
        for name in ORDER:
            convert(name, *SFX[name])
    write_header()


if __name__ == "__main__":
    main()

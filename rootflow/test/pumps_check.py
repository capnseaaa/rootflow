"""Vael pump checks (v0.11). Writes test/pumps.txt (v4 + pump steps), runs it, and checks:
1. When the timer runs out, a pump starts on living land, outside every home's reach, away from the player.
2. A pump drains the nearest living tiles (about one per PUMP_DRAIN frames) and never inside a home's reach.
3. Pressing A next to a pump shuts it down: the tile becomes DEAD, +3 stone, 1 charge spent, counted as stopped.
Run from rootflow/test:  python3 pumps_check.py
"""
import re
import subprocess
import sys

sys.path.insert(0, "../tools")
import build_data as bd  # noqa: E402

GRASSY = {bd.GRASS, bd.GRASS_TUFT, bd.FLOWERS, bd.TREE}
VAEL_PUMP = 38
REACH = {0: 8}           # all homes are level 1 after v4


def dump_lines(area):
    base = area * 1024
    return [f"0 0 @" + ",".join(f"$maps+{base + 4 * j}" for j in range(i, i + 16)) for i in range(0, 256, 16)]


def decode(vals):
    return [(v >> (8 * k)) & 255 for v in vals for k in range(4)]


def protected(area, x, y):
    for a, hx, hy in bd.HOME_SITES:
        if a == area and (x - hx) ** 2 + (y - hy) ** 2 <= 8 * 8:
            return True
    return False


def main():
    v4 = open("v4.txt").read().rstrip("\n").split("\n")
    steps = ["# v0.11 Vael pumps (generated by pumps_check.py; run that, not this file directly)"] + v4
    # 1. spawn
    steps += ["# 1: the pump timer runs out", "0 0 !$pump_timer=7199", "3 0 u1_spawned.ppm",
              "0 0 @$pump_on,$pump_x,$pump_y,$px,$py,$cur_area"]
    steps += dump_lines(0) + dump_lines(1) + dump_lines(2)
    # 2. a pump placed at valley (15,21), on living land outside home reach
    steps += ["# 2: a valley pump at (15,21); stop timers so nothing else spawns",
              "0 0 !$pump_on=1,$pump_x=15,$pump_y=21,$pump_drain=0,$pump_timer=0",
              "0 0 !$maps+684=637731587"] + dump_lines(0)
    steps += ["1200 0", "0 0 !$pump_timer=0"] + dump_lines(0)
    # 3. shut it down from (15,22), facing up
    steps += ["# 3: shut it down", "0 0 !$px=240,$py=346", "10 0", "1 64",
              "0 0 @$stone,$pumps_stopped,$active,$spirits+16,$spirits+44,$spirits+72,$spirits+100",
              "2 1", "30 0 u2_shut_down.ppm",
              "0 0 @$stone,$pumps_stopped,$pump_on,$spirits+16,$spirits+44,$spirits+72,$spirits+100,$maps+684"]
    open("pumps.txt", "w").write("\n".join(steps) + "\n")

    out = subprocess.run(["sh", "run.sh", "test/pumps.txt"], capture_output=True, text=True).stdout
    lines = [l for l in out.splitlines() if "]=" in l]
    vals = lambda l: [int(v) & 0xFFFFFFFF for v in re.findall(r"=(-?\d+)", l)]
    # the last 1 + 48 + 16 + 16 + 2 peek lines belong to this test
    tail = lines[-(1 + 48 + 16 + 16 + 2):]
    ok = True

    def check(cond, msg):
        nonlocal ok
        print(("PASS " if cond else "FAIL ") + msg)
        ok &= bool(cond)

    # 1. spawn
    on, xs, ys, ppx, ppy, area_now = vals(tail[0])
    on_b, x_b, y_b = decode([on])[:3], decode([xs])[:3], decode([ys])[:3]
    maps = [decode(sum((vals(l) for l in tail[1 + 16 * a:17 + 16 * a]), [])) for a in range(3)]
    started = [a for a in range(3) if on_b[a]]
    check(len(started) == 1, f"exactly one pump started (areas {started})")
    for a in started:
        x, y = x_b[a], y_b[a]
        check(maps[a][y * 32 + x] == VAEL_PUMP, f"area {a}: pump tile at ({x},{y})")
        check(not protected(a, x, y), f"area {a}: ({x},{y}) is outside every home's reach")
        if a == area_now:
            d2 = (x - ((ppx + 8) >> 4)) ** 2 + (y - ((ppy + 12) >> 4)) ** 2
            check(d2 >= 36, f"pump is at least 6 tiles from the player (d^2={d2})")

    # 2. drain
    before = decode(sum((vals(l) for l in tail[49:65]), []))
    after = decode(sum((vals(l) for l in tail[65:81]), []))
    near = [(x, y) for y in range(32) for x in range(32) if (x - 15) ** 2 + (y - 21) ** 2 <= 36]
    lost = [(x, y) for x, y in near if before[y * 32 + x] in GRASSY and after[y * 32 + x] not in GRASSY]
    check(4 <= len(lost) <= 6, f"1200 frames drained {len(lost)} living tiles near the pump (expect ~5)")
    check(all(not protected(0, x, y) for x, y in lost), "no drained tile is inside a home's reach")
    gained = [(x, y) for y in range(32) for x in range(32)
              if before[y * 32 + x] in GRASSY and after[y * 32 + x] not in GRASSY and (x, y) not in near]
    check(not gained, f"nothing outside the pump's reach was drained ({len(gained)})")
    if lost:
        far_left = max((x - 15) ** 2 + (y - 21) ** 2 for x, y in lost)
        still = [((x - 15) ** 2 + (y - 21) ** 2) for x, y in near if after[y * 32 + x] in GRASSY and not protected(0, x, y)]
        check(not still or far_left <= min(still), "it drained the nearest living tiles first")

    # 3. shut down
    b = vals(tail[81]); a = vals(tail[82])
    stone0, stopped0 = b[0], b[1]
    energy0 = b[3:7]
    stone1, stopped1, on1 = a[0], a[1], a[2]
    energy1 = a[3:7]
    check(stone1 == stone0 + 3, f"+3 stone ({stone0} -> {stone1})")
    check(stopped1 == stopped0 + 1, f"pumps stopped {stopped0} -> {stopped1}")
    check(decode([on1])[0] == 0, "the valley pump is off")
    check((a[7] >> 24) & 255 == bd.DEAD, "the pump tile became dead ground")
    check(sum(energy0) - sum(energy1) == 1, f"one charge spent ({energy0} -> {energy1})")
    print("ALL PASS" if ok else "SOME CHECKS FAILED")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()

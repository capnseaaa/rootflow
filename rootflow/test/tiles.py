"""Decode a peek of four map tiles (one 32-bit word) into tile names. Usage: python3 tiles.py VALUE..."""
import sys
NAMES = ("DEAD DEAD_CRACK DIRT GRASS GRASS_TUFT FLOWERS TREE DEAD_TREE ROCK WATER WATER_B BRIDGE THORN "
         "HOMESITE CHEST CHEST_OPEN WRECK DRY_GRASS PEBBLES MENHIR DRY_RIVER DRY_BRIDGE PATH FLOWERBED "
         "FLOWERBED_EMPTY SAPLING FRUIT_TREE FRUIT_TREE_BARE LANTERN BENCH DAM LEVER LEVER_PULLED LOST_STONE "
         "BLOSSOM FOUNTAIN STATUE PINWHEEL VAEL_PUMP VAEL_PUMP_B "
         + " ".join(f"{h}{l}_{p}" for h in ("GROVE", "SPRING", "CAIRN", "NOOK") for l in (1, 2) for p in ("ROOF", "BASE"))
         + " SPRING1_RING1 SPRING1_RING2 SPRING2_RING1 SPRING2_RING2 SPRING2_SPRAY CAIRN1_GLOW CAIRN2_GLOW"
           " NOOK1_SWING NOOK2_SPIN STUMP STUMP_GRASS CHEST_GRASS CHEST_OPEN_GRASS WRECK_GRASS "
         + " TRUNK_BLOCK ROOT_TIP_DEAD ROOT_TIP_ALIVE CLAMP DRY_POOL TRUNK_GRASS MUSH_LAMP LEAF_SWING ACORN_BENCH FLOWER_ARCH PEBBLE_PATH DEW_POND ROCK_GRASS SLUDGE LILY_PAD REEDS VAEL_PIPE"
         " BOG_WATER BOG_WATER_B BOG_PAD MOSS MUSHROOMS SWAMP_TREE SWAMP_TREE_ALIVE LOG SWAMP_TOP SWAMP_TOP_ALIVE"
         + "".join(f" BOG_EDGE{k}" for k in range(15)) + "".join(f" WATER_EDGE{k}" for k in range(15))
         + " BURNT_TREE BURNT_FRUIT_TREE BURNT_LOG LANTERN_COLD LANTERN_LIT CAMPFIRE_COLD CAMPFIRE_LIT LOG_SEAT SMOKE_STACK BURNT_FENCE DARKNESS ASH_LANE CHARRED_BRUSH").split()
for v in sys.argv[1:]:
    w = int(v) & 0xFFFFFFFF
    print(" ".join(NAMES[(w >> (8 * k)) & 255] if ((w >> (8 * k)) & 255) < len(NAMES) else "?" for k in range(4)))
